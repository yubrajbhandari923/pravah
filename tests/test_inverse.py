def test_direct_agrees_with_linear_on_tiny_fixture():
    """Both minimise the same convex bounded least-squares problem; the residual is exactly affine in q, so the
    finite-difference Jacobian is exact up to round-off.  Optimiser tolerances 1e-14 -> agree to ~1e-6 relative; we
    assert 1e-5 (noisy data, so neither equals the truth)."""
    srcs = SRC[:2]
    sc = make_scenario(domain=Domain(10_000.0, 10_000.0, 12, 12), sources=srcs,
                       times=Times(duration=1800.0, dt=300.0, output_interval=600.0))
    q = Q_TRUE[:2]
    lay = SensorLayout(("a", "b", "c", "d"), (4000.0, 5500.0, 3500.0, 6000.0), (3000.0, 6500.0, 2800.0, 7000.0))
    obs = observe(simulate(sc, q).concentration, lay, ObservationSpec((600.0, 1200.0, 1800.0), 0.05, 3))
    c = ResponseCache()
    lin = fit_sources(sc, obs, InferenceOptions(method="linear"), c)
    dr = fit_sources(sc, obs, InferenceOptions(method="direct"), c)
    assert lin.success and dr.success
    assert np.max(np.abs(lin.q_hat - dr.q_hat) / np.abs(lin.q_hat)) < 1e-5
    assert abs(lin.weighted_residual - dr.weighted_residual) < 1e-6 * lin.weighted_residual
    assert np.allclose(lin.singular_values, dr.singular_values)
    assert not np.allclose(lin.q_hat, q, rtol=1e-3)  # noise is really present


def test_tikhonov_shrinks_toward_prior_and_is_reported(cache, truth):
    obs = noiseless_obs(truth, std=0.0)
    prior = np.array([2.0e5, 5.0e4, 1.0e5])
    d0 = np.linalg.norm(fit_sources(SC, obs, InferenceOptions(), cache).q_hat - prior)
    dists = []
    for alpha in (1.0, 1e3, 1e8):
        f = fit_sources(SC, obs, InferenceOptions(alpha=alpha, prior=tuple(prior)), cache)
        dists.append(np.linalg.norm(f.q_hat - prior))
        assert f.alpha == alpha and np.array_equal(f.prior, prior)
        assert f.reg_condition <= f.condition
    assert d0 > dists[0] > dists[1] > dists[2]
    assert dists[2] < 1e-3 * d0  # huge alpha ~ prior
    # alpha > 0 with the default zero prior pulls estimates down
    f = fit_sources(SC, obs, InferenceOptions(alpha=1e3), cache)
    assert np.all(f.q_hat < Q_TRUE)


