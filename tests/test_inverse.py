SRC = (GaussianSource("S1", 2500.0, 2500.0, 600.0), GaussianSource("S2", 4000.0, 6000.0, 600.0),
       GaussianSource("S3", 6500.0, 3500.0, 600.0))
Q_TRUE = np.array([1.0e5, 1.5e5, 8.0e4])
OBS_T = tuple(float(t) for t in range(600, 3601, 600))


def make_scenario(**kw) -> Scenario:
    base = dict(domain=Domain(10_000.0, 10_000.0, 20, 20), sources=SRC,
                transport=Transport(wind=(WindSegment(0.0, 1.0, 0.3),), K=100.0, lam=1 / 21600.0, H=500.0),
                times=Times(duration=3600.0, dt=120.0, output_interval=600.0))
    base.update(kw)
    return Scenario(**base)


SC = make_scenario()
GOOD = SensorLayout(tuple(f"s{i}" for i in range(8)),
                    (4000.0, 5500.0, 7500.0, 3500.0, 5500.0, 6000.0, 8000.0, 5000.0),
                    (3000.0, 6500.0, 4000.0, 2800.0, 3000.0, 6800.0, 4300.0, 5000.0))


@pytest.fixture(scope="module")
def cache() -> ResponseCache:
    return ResponseCache()


@pytest.fixture(scope="module")
def truth() -> xr.DataArray:
    return simulate(SC, Q_TRUE).concentration


def rel_err(a, b) -> float:
    return float(np.max(np.abs(np.asarray(a) - np.asarray(b))) / max(np.max(np.abs(b)), 1e-300))


