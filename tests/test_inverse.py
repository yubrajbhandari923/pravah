def test_heldout_sensors_excluded_bitwise(cache, truth):
    obs = observe(truth, GOOD, ObservationSpec(OBS_T, 0.05, 11))
    held = ("s2", "s5")
    opt = InferenceOptions(heldout_ids=held)
    f1 = fit_sources(SC, obs, opt, cache)
    vals = obs.values.copy(deep=True)
    for h in held:
        vals.loc[{"sensor": h}] = 1e6 * np.random.default_rng(0).standard_normal(len(OBS_T))
    f2 = fit_sources(SC, Observations(vals, obs.noise_std, obs.layout, obs.times), opt, cache)
    assert np.array_equal(f1.q_hat, f2.q_hat) and f1.weighted_residual == f2.weighted_residual
    assert f1.n_obs == len(OBS_T) * (len(GOOD) - 2) and f1.heldout_ids == held
    # and it equals fitting the subset layout directly
    keep = [i for i, s in enumerate(GOOD.ids) if s not in held]
    sub = Observations(obs.values.isel(sensor=keep), obs.noise_std[keep], GOOD.select(keep), obs.times)
    assert np.array_equal(fit_sources(SC, sub, InferenceOptions(), cache).q_hat, f1.q_hat)
    # changing a used sensor does change the fit
    vals = obs.values.copy(deep=True)
    vals.loc[{"sensor": "s0"}] = vals.loc[{"sensor": "s0"}] + 1.0
    f3 = fit_sources(SC, Observations(vals, obs.noise_std, obs.layout, obs.times), opt, cache)
    assert not np.array_equal(f1.q_hat, f3.q_hat)


