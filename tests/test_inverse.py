@pytest.mark.parametrize("kw", [
    dict(),
    dict(initial=Initial("uniform", 2.0)),
    dict(initial=Initial("gaussian", 5.0, 3000.0, 4000.0, 800.0)),
    dict(boundary=Boundary("open", 1.5)),
    dict(initial=Initial("gaussian", 5.0, 3000.0, 4000.0, 800.0), boundary=Boundary("open", 1.5)),
], ids=["zero", "uniform_ic", "gaussian_ic", "background", "gaussian_ic+background"])
def test_decomposition_matches_direct_simulation(kw):
    sc = make_scenario(**kw)
    resp = ResponseCache().get(sc)
    q = np.array([7.0e4, 0.0, 2.2e5])
    direct = simulate(sc, q).concentration.values
    got = resp.field(q).values
    assert np.max(np.abs(got - direct)) <= 1e-6 * np.max(np.abs(direct)) + 1e-9
    # base really is the q = 0 run, and for nonzero IC/background it is not trivially zero
    assert np.array_equal(resp.base, simulate(sc, np.zeros(3)).concentration.values)
    if kw:
        assert resp.base.max() > 0.1


def test_operator_matches_observations_sample(cache, truth):
    resp = cache.get(SC)
    times = [600.0, 1000.0, 3600.0]  # includes a time between stored outputs
    b, A = resp.operator(GOOD, times)
    expect = sample(truth, GOOD, times).values.reshape(-1)  # (time, sensor) flattened time-major
    assert A.shape == (3 * len(GOOD), 3)
    assert rel_err(b + A @ Q_TRUE, expect) < 1e-6


# ---------------------------------------------------------------- recovery / identifiability
def noiseless_obs(truth_field, layout=GOOD, std=0.0, seed=0):
    return observe(truth_field, layout, ObservationSpec(OBS_T, std, seed))


def test_noise_free_recovery(cache, truth):
    """The data are generated by the same linear model the fit inverts, so the exact q is a zero-residual solution;
    with full rank the only error is round-off in the solves (~1e-10), far below 1e-4."""
    fit = fit_sources(SC, noiseless_obs(truth), InferenceOptions(), cache)
    assert fit.success and fit.rank == 3 and np.isfinite(fit.condition)
    assert np.max(np.abs(fit.q_hat - Q_TRUE) / Q_TRUE) < 1e-4
    assert fit.weighted_residual < 1e-6
    assert fit.n_obs == len(OBS_T) * len(GOOD)
    # reconstruction: true forward run and the fast linear one agree and reproduce the truth
    assert rel_err(reconstruct(SC, fit).concentration, truth) < 1e-4
    assert rel_err(reconstruct_linear(cache.get(SC), fit), truth) < 1e-4


def test_alpha_zero_and_report_fields(cache, truth):
    fit = fit_sources(SC, noiseless_obs(truth), InferenceOptions(alpha=0.0), cache)
    assert fit.alpha == 0.0 and np.all(fit.prior == 0) and np.all(fit.q_scale == 1e5)
    assert fit.method == "linear" and fit.heldout_ids == () and fit.runtime_s > 0
    assert fit.singular_values.shape == (3,)
    np.testing.assert_allclose(fit.reg_singular_values, fit.singular_values)


def test_degenerate_far_upwind_sensors_flagged(cache, truth):
    """All sensors in the upwind (west) top corner, outside any source influence: A is numerically zero."""
    lay = SensorLayout(("a", "b", "c"), (600.0, 800.0, 700.0), (9400.0, 9200.0, 9300.0))
    fit = fit_sources(SC, noiseless_obs(truth, lay), InferenceOptions(), cache)
    # The columns are ~1e-15 ug/m^3 per ug/s, but not exactly zero (diffusion tails), so the purely relative rank
    # test may still count 3: the flag is then the enormous condition number and the negligible s_max (whitened
    # units; sigma = 1 here, so the data carry no information on q).
    assert fit.rank < 3 or fit.condition > 1e10
    assert fit.singular_values[0] < 1e-6


