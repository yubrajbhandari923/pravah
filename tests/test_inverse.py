def test_noise_weighted_fit_matches_predicted_covariance(cache, truth):
    """Whitened least squares: cov(theta_hat) = (Aw^T Aw)^-1 when no bound is active.  Check one fixed-seed draw within
    4 predicted std, then the empirical std over 300 draws against the prediction (sampling error ~4%; we allow 20%)."""
    sigma = np.linspace(0.001, 0.003, len(GOOD))  # different noise per sensor -> weighting matters
    resp = cache.get(SC)
    _, A = resp.operator(GOOD, OBS_T)
    w = np.broadcast_to(1.0 / sigma, (len(OBS_T), len(GOOD))).reshape(-1)
    pred_std = np.sqrt(np.diag(np.linalg.inv((A * w[:, None]).T @ (A * w[:, None]))))
    assert np.all(Q_TRUE > 20 * pred_std)  # bounds inactive
    errs = []
    for seed in range(300):
        obs = observe(truth, GOOD, ObservationSpec(OBS_T, tuple(sigma), seed))
        errs.append(fit_sources(SC, obs, InferenceOptions(), cache).q_hat - Q_TRUE)
    errs = np.array(errs)
    assert np.all(np.abs(errs[0]) < 4 * pred_std)
    ratio = errs.std(axis=0, ddof=1) / pred_std
    assert np.all((ratio > 0.8) & (ratio < 1.25)), ratio
    assert np.all(np.abs(errs.mean(axis=0)) < 4 * pred_std / np.sqrt(300))  # unbiased
    # chi^2 of the data residual: (m - n) expected
    obs = observe(truth, GOOD, ObservationSpec(OBS_T, tuple(sigma), 0))
    f = fit_sources(SC, obs, InferenceOptions(), cache)
    assert abs(f.weighted_residual**2 - (f.n_obs - 3)) < 5 * np.sqrt(2 * (f.n_obs - 3))


def test_effective_rank_and_q_std_match_empirical(cache, truth):
    sigma = np.linspace(0.001, 0.003, len(GOOD))
    obs = observe(truth, GOOD, ObservationSpec(OBS_T, tuple(sigma), 0))
    fit = fit_sources(SC, obs, InferenceOptions(), cache)
    _, A = cache.get(SC).operator(GOOD, OBS_T)
    w = np.broadcast_to(1.0 / sigma, (len(OBS_T), len(GOOD))).reshape(-1)
    pred_std = np.sqrt(np.diag(np.linalg.inv((A * w[:, None]).T @ (A * w[:, None]))))
    np.testing.assert_allclose(fit.q_std, pred_std, rtol=1e-6)  # same quantity the covariance test checks empirically
    assert fit.effective_rank == int(np.sum(fit.singular_values > 1.0)) == 3  # q_scale 1e5 >> q_std ~ 1e3
    # alpha > 0 can only shrink q_std
    reg = fit_sources(SC, obs, InferenceOptions(alpha=10.0), cache)
    assert np.all(reg.q_std < fit.q_std)


